// Package watermark 是**前端渲染的盲水印**的唯一实现：一套几何与编码，两个
// 方向——浏览器拿 Tile 的 PNG 当 repeating background 铺满页面，服务端拿截图
// 跑 Extract 把码解出来。
//
// 为什么是"前端渲染"而不是服务端烧进图片：水印要盖住的是**页面内容被截图带走**
// 这件事，不是图片被下载这件事。由 CSS 背景铺一层极淡的点阵，截图里就会带上它，
// 而 PDF 打印、整屏复制、聊天里转发截屏都在覆盖范围内。
//
// 几个取值的取舍写在各自定义处，这里只说三件全局的事：
//
//  1. **格子是二值颜色，不是"有/无"**。一格要么画黑、要么画白，因此不论页面底色
//     是白页、深色面板还是照片，格子相对底色的亮度差方向都是固定的（黑格变暗、
//     白格变亮）。只加亮的那种做法在白底上会完全消失——那正是最常见的页面。
//
//  2. **格子取值被掩码打散**。一整个 4×4 格子的像素同色会显出方块纹；让每个格子
//     再 XOR 一个只依赖它在块内坐标的固定掩码后，每块看起来是同一片噪声点阵，
//     数据位只决定这块是否整体反相，肉眼看到的是均匀颗粒而不是格子。
//
//  3. **帧尺寸是块尺寸的整数倍**，因此按帧平铺天然无缝，不需要在边界上做任何
//     过渡（也别加分隔线——那会在图上留一道可见的接缝）。
//
// 这个包只做算法：不碰数据库、不碰网络、不碰 HTTP。它的输入是一张 image.Image，
// 输出是一串码；其余（什么时候铺、铺在哪、日志怎么记）都由调用方决定。
package watermark
